const SOZLUK: Record<Dil, SahaMetinleri> = { tr, en };
export const metinler = (dil: Dil): SahaMetinleri => SOZLUK[dil];

/** Telefonun dili Türkçe değilse İngilizce. */
export function sistemDili(): Dil {
  const d = typeof navigator !== 'undefined' ? (navigator.language ?? '') : '';
  return !d || d.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

/** KML'deki Google Earth balonu için etiketler. */
export function kmlEtiketleri(m: SahaMetinleri): SahaKmlEtiketleri {
  return {
    ...m.kml,
    kotMetni: m.kot,
    sayi: (x) => m.sayi(x, 2),
    zaman: (z) => m.kml.zaman(new Date(z).toLocaleString(m.yerel, { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' })),
  };
}
